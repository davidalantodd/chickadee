// Builds netlify/lib/places-data.js, the town list used to label observations with their nearest town.
//
// Source: GeoNames (https://www.geonames.org, CC BY 4.0): towns with a population of 1,000 or more,
// plus the names of states/provinces (admin1) and countries.
//
// Run with: node scripts/build-places.mjs   (needs curl and unzip)

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const BASE_URL = 'https://download.geonames.org/export/dump/'
const OUTPUT = new URL('../netlify/lib/places-data.js', import.meta.url)

// Populated-place feature codes left out: neighbourhoods (PPLX) and historical, abandoned or destroyed places
const EXCLUDED_FEATURE_CODES = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW'])

const workDir = mkdtempSync(join(tmpdir(), 'geonames-'))
const download = (file) => {
    const path = join(workDir, file)
    execFileSync('curl', ['-sSfL', '-o', path, BASE_URL + file])
    return path
}
const lines = (text) => text.split('\n').filter(line => line && !line.startsWith('#'))

try {
    const citiesText = execFileSync('unzip', ['-p', download('cities1000.zip'), 'cities1000.txt'],
        { maxBuffer: 1024 * 1024 * 1024 }).toString('utf8')
    const admin1Text = readFileSync(download('admin1CodesASCII.txt'), 'utf8')
    const countryText = readFileSync(download('countryInfo.txt'), 'utf8')

    // "US.VA" -> "Virginia"
    const regions = {}
    for (const line of lines(admin1Text)) {
        const [code, name] = line.split('\t')
        regions[code] = name
    }

    // "US" -> "United States"
    const countries = {}
    for (const line of lines(countryText)) {
        const columns = line.split('\t')
        countries[columns[0]] = columns[4]
    }

    // [name, lat, lng, "US.VA"], with coordinates trimmed to 4 decimal places (about 10 m)
    const places = []
    for (const line of lines(citiesText)) {
        const columns = line.split('\t')
        if (EXCLUDED_FEATURE_CODES.has(columns[7])) continue
        places.push([columns[1], +(+columns[4]).toFixed(4), +(+columns[5]).toFixed(4), `${columns[8]}.${columns[10]}`])
    }

    writeFileSync(OUTPUT, [
        '/* eslint-disable */',
        '// Generated by scripts/build-places.mjs from GeoNames (https://www.geonames.org, CC BY 4.0). Do not edit.',
        `export const regions = ${JSON.stringify(regions)}`,
        `export const countries = ${JSON.stringify(countries)}`,
        `export const places = ${JSON.stringify(places)}`,
        '',
    ].join('\n'))

    console.log(`Wrote ${places.length} places, ${Object.keys(regions).length} regions, ${Object.keys(countries).length} countries`)
} finally {
    rmSync(workDir, { recursive: true, force: true })
}
